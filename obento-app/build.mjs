// Builds the store app's web files (web/ -> www/) and fills in the native projects' settings
// from app.config.json. Run `npm run sync` after any change to web/ or app.config.json.
//   - www/ gets everything the game needs, nothing else (no tests, no family photos)
//   - js/edition.js gets the store links and ad / product ids
//   - the Capacitor runtime is added so the game can talk to the ads and purchase plugins
//   - android/ and ios/ (once added with `npx cap add`) get the app id, version, AdMob app id,
//     portrait orientation, the tracking prompt text and the app icons
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const here = path.dirname(new URL(import.meta.url).pathname);
const cfg = JSON.parse(fs.readFileSync(path.join(here, 'app.config.json'), 'utf8'));
const web = path.join(here, 'web'), www = path.join(here, 'www');
const SKIP = new Set(['tests', 'README.md', 'package.json', 'node_modules', 'sw.js']);

// 1. web files
fs.rmSync(www, { recursive: true, force: true });
fs.cpSync(web, www, { recursive: true, filter: (src) => !SKIP.has(path.basename(src)) || path.dirname(src) !== web });
for (const f of ['img/cameo.jpg', 'img/rare.png']) if (fs.existsSync(path.join(www, f))) throw new Error(`${f} must not ship in the app`);

// 2. edition
const ads = { testing: !!cfg.ads.testing, product: cfg.ads.product,
  android: { interstitial: cfg.ads.android.interstitial }, ios: { interstitial: cfg.ads.ios.interstitial } };
fs.writeFileSync(path.join(www, 'js/edition.js'), `// generated by obento-app/build.mjs from app.config.json
export const EDITION = ${JSON.stringify({ store: true, version: cfg.version, shareUrl: cfg.shareUrl, privacyUrl: cfg.privacyUrl, ads }, null, 2)};
`);

// 3. Capacitor runtime (the game is plain ES modules, no bundler)
fs.copyFileSync(path.join(here, 'node_modules/@capacitor/core/dist/capacitor.js'), path.join(www, 'vendor/capacitor.js'));
const indexPath = path.join(www, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
html = html.replace('<script src="vendor/matter.min.js"></script>', '<script src="vendor/capacitor.js"></script>\n<script src="vendor/matter.min.js"></script>');
fs.writeFileSync(indexPath, html);

// 4. native projects
const edit = (file, fn) => { if (!fs.existsSync(file)) return false; const a = fs.readFileSync(file, 'utf8'), b = fn(a); if (a !== b) fs.writeFileSync(file, b); return true; };
const icon = path.join(web, 'icons/icon-512.png'), maskable = path.join(web, 'icons/icon-maskable-512.png');
const resize = (src, size, out, flat = false) => { fs.mkdirSync(path.dirname(out), { recursive: true }); execFileSync('python3', ['-I', path.join(here, 'tools/resize.py'), src, String(size), out, ...(flat ? ['flat'] : [])]); };

const android = path.join(here, 'android');
if (fs.existsSync(android)) {
  edit(path.join(android, 'app/build.gradle'), (s) => s
    .replace(/versionCode \d+/, `versionCode ${cfg.build}`)
    .replace(/versionName "[^"]*"/, `versionName "${cfg.version}"`));
  edit(path.join(android, 'app/src/main/AndroidManifest.xml'), (s) => {
    s = s.replace(/\s*<meta-data android:name="com.google.android.gms.ads.APPLICATION_ID"[^>]*\/>/, '');
    s = s.replace('<application', '<application').replace(/(<application[^>]*>)/, `$1\n        <meta-data android:name="com.google.android.gms.ads.APPLICATION_ID" android:value="${cfg.ads.android.app}"/>`);
    if (!s.includes('android:screenOrientation')) s = s.replace('<activity', '<activity\n            android:screenOrientation="portrait"');
    return s;
  });
  const res = path.join(android, 'app/src/main/res');
  for (const [d, px, fg] of [['mdpi', 48, 108], ['hdpi', 72, 162], ['xhdpi', 96, 216], ['xxhdpi', 144, 324], ['xxxhdpi', 192, 432]]) {
    resize(icon, px, path.join(res, `mipmap-${d}/ic_launcher.png`));
    resize(icon, px, path.join(res, `mipmap-${d}/ic_launcher_round.png`));
    resize(maskable, fg, path.join(res, `mipmap-${d}/ic_launcher_foreground.png`));
  }
  // launch screens: replace every splash.png with the game's own, same size as the one it replaces
  const size = (f) => execFileSync('python3', ['-I', '-c', 'import sys; from PIL import Image; print(*Image.open(sys.argv[1]).size)', f]).toString().trim().split(' ').map(Number);
  for (const d of fs.readdirSync(res)) {
    const f = path.join(res, d, 'splash.png');
    if (fs.existsSync(f)) { const [w, h] = size(f); execFileSync('python3', ['-I', path.join(here, 'tools/splash.py'), icon, String(w), String(h), f]); }
  }
  edit(path.join(res, 'values/ic_launcher_background.xml'), (s) => s.replace(/<color name="ic_launcher_background">[^<]*<\/color>/, '<color name="ic_launcher_background">#FFF6E4</color>'));
}

const ios = path.join(here, 'ios/App/App');
if (fs.existsSync(ios)) {
  edit(path.join(ios, 'Info.plist'), (s) => {
    const set = (key, xml) => {
      const re = new RegExp(`\\s*<key>${key}</key>\\s*(<string>[^<]*</string>|<array>[\\s\\S]*?</array>|<true/>|<false/>)`);
      s = s.replace(re, '');
      s = s.replace(/<dict>/, `<dict>\n\t<key>${key}</key>\n\t${xml}`);
    };
    set('GADApplicationIdentifier', `<string>${cfg.ads.ios.app}</string>`);
    set('NSUserTrackingUsageDescription', '<string>あなたに合った広告を表示するために使用します。許可しなくてもゲームはそのまま遊べます。</string>');
    set('NSPhotoLibraryUsageDescription', '<string>ごほうび写真とレアキャラの画像に使う写真を選ぶために使用します。写真は端末の中だけに保存されます。</string>');
    set('UISupportedInterfaceOrientations', '<array>\n\t\t<string>UIInterfaceOrientationPortrait</string>\n\t</array>');
    set('UIRequiresFullScreen', '<true/>');
    set('SKAdNetworkItems', '<array>\n\t\t<dict>\n\t\t\t<key>SKAdNetworkIdentifier</key>\n\t\t\t<string>cstr6suwn9.skadnetwork</string>\n\t\t</dict>\n\t</array>');
    return s;
  });
  edit(path.join(here, 'ios/App/App.xcodeproj/project.pbxproj'), (s) => s
    .replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${cfg.version};`)
    .replace(/CURRENT_PROJECT_VERSION = [^;]+;/g, `CURRENT_PROJECT_VERSION = ${cfg.build};`));
  const splash = path.join(ios, 'Assets.xcassets/Splash.imageset');
  if (fs.existsSync(splash)) for (const f of fs.readdirSync(splash)) if (f.endsWith('.png')) execFileSync('python3', ['-I', path.join(here, 'tools/splash.py'), icon, '2732', '2732', path.join(splash, f)]);
  const set = path.join(ios, 'Assets.xcassets/AppIcon.appiconset');
  if (fs.existsSync(set)) {
    for (const f of fs.readdirSync(set)) if (f.endsWith('.png')) resize(icon, 1024, path.join(set, f), true);
  }
}
console.log(`built www/ for ${cfg.appName} ${cfg.version} (${cfg.build})${cfg.ads.testing ? ' with TEST ads' : ''}`);
