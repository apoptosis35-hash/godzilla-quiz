# Writes sw.js: precaches the game, three.js and every model/texture it loads, versioned by a hash of their contents.
#   python3 tools/build_sw.py
import hashlib, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); GAME = os.path.dirname(HERE); ROOT = os.path.dirname(GAME)
files = ['./', 'index.html', 'manifest.webmanifest', 'css/style.css'] + sorted(
    os.path.relpath(os.path.join(d, f), GAME) for d, _, fs in os.walk(GAME) for f in fs
    if f.endswith(('.js', '.png')) and '/tests' not in d and '/tools' not in d and f != 'sw.js')
town = open(os.path.join(GAME, 'js/town.js'), encoding='utf-8').read()
block = town[town.index('export const MODELS'):town.index('};', town.index('export const MODELS'))]
models = re.findall(r"'([a-z0-9_]+)'", block.split('=', 1)[1])
assets = ['../uminagi-assets/materials.json', '../uminagi-assets/textures/textures.json'] + [f'../uminagi-assets/glb/{m}.glb' for m in models]
assets += sorted('../uminagi-assets/textures/' + f for f in os.listdir(os.path.join(ROOT, 'uminagi-assets/textures')) if f.endswith('.jpg'))
h = hashlib.sha1()
for f in files + assets:
    p = os.path.normpath(os.path.join(GAME, f)) if f != './' else os.path.join(GAME, 'index.html')
    h.update(open(p, 'rb').read())
version = h.hexdigest()[:10]
lst = ',\n  '.join(repr(f) for f in files + assets)
open(os.path.join(GAME, 'sw.js'), 'w', encoding='utf-8').write(f"""// Offline cache for 海凪の港町 (generated by tools/build_sw.py — do not edit by hand).
// Cache-first; a new version (content hash) re-downloads everything once.
const CACHE = 'uminagi-{version}';
const FILES = [
  {lst},
];
self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('uminagi-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async (c) => {{
    const hit = await c.match(req, {{ ignoreSearch: true }});
    return hit || fetch(req).then((res) => {{ if (res.ok) c.put(req, res.clone()); return res; }});
  }}));
}});
""")
print(len(files) + len(assets), 'files, version', version)
